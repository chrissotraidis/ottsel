OBJS=()
for src in $COMMON_SRC $KERNEL_SRC; do
  name="$(echo "$src" | tr '/' '_' | sed 's/\.\(cpp\|cc\|s\|c\)$/.o/')"
  case "$src" in
    *.c) xcrun --sdk "$SDK" clang -O2 -target "$TARGET" -isysroot "$SDKROOT" \
           -mios-version-min="$DEPLOY" -c "$WORKTREE/$src" -o "$OBJ/$name" ;;
    *) compile "$WORKTREE/$src" "$OBJ/$name" ;;
  esac
  OBJS+=("$OBJ/$name")
done

ar rcs "$APP_BUILD/libottsel-runtime.tmp.a" "${OBJS[@]}"
mv -f "$APP_BUILD/libottsel-runtime.tmp.a" "$APP_BUILD/libottsel-runtime.a"
printf '%s\n' "$SIGNED_GSTATE" > "$APP_BUILD/signed-gstate-mode"
printf '%s\n' "$SIGNED_EXPORT_BANKS" > "$APP_BUILD/signed-export-bank-mode"
echo "runtime lib: $APP_BUILD/libottsel-runtime.a ($((${#OBJS[@]})) objects)"
fi

echo "== [3/4] compile + link app =="
if ! $SHELL_ONLY; then
mkdir -p "$SLICE_DIR"
echo "== [3a/4] generate A1.1 slice (offline linker) =="
cmake --build "$WORKTREE/build/h1" --target ottsel-a11-slice -j 8
"$WORKTREE/build/h1/goalc/ottsel-a11-slice" "$SLICE_DIR"
xcrun --sdk "$SDK" clang "${COMMON_FLAGS[@]}" -c "$SLICE_DIR/slice.s" -o "$OBJ/a11_slice.o"
fi
if $SIGNED_ENABLED; then
  mkdir -p "$SIGNED_DIR"
  if ! $SHELL_ONLY; then
    # Read actual allocator constants before laying out a shared module arena.
    cat > "$SIGNED_DIR/layout-values.cpp" <<'CPP'
#include "game/kernel/common/memory_layout.h"
#include <cstdio>
int main() { std::printf("%u %u\n", HEAP_START, GLOBAL_HEAP_END); }
CPP
    xcrun --sdk macosx clang++ -std=c++20 -I"$WORKTREE" \
      "$SIGNED_DIR/layout-values.cpp" -o "$SIGNED_DIR/layout-values"
    "$SIGNED_DIR/layout-values" > "$SIGNED_DIR/layout-values.txt"
    SIGNED_GENERATION="$(mktemp -d "$SIGNED_DIR/modules.XXXXXX")"
    SIGNED_INPUT_DIR="$SIGNED_GENERATION/modules"
    python3 - "$REPO_DIR" "$WORKTREE" "$SIGNED_GENERATION" "$SIGNED_NAMES" "$SIGNED_MODULE_LIST" <<'PYTHON'
import json,pathlib,struct,subprocess,sys
repo,work,transaction=map(pathlib.Path,sys.argv[1:4]);names=sys.argv[4].split();selected=sys.argv[5]
heap_start,heap_end=map(int,(transaction.parent/'layout-values.txt').read_text().split())
emitter=work/'build/h1/goalc/ottsel-a11-slice';source=transaction/'emitted';output=transaction/'modules'
def run(args):subprocess.run(list(map(str,args)),check=True)
for name in names:
    obj=work/'out/jak1/obj'/(name+'.o')
    # A module is release-debug exactly when its own object carries a debug
    # segment (segment-1 source text size); derive policy from the object so
    # arbitrary generated lists never inherit the canonical KERNEL name set.
    extra=['--release-no-debug'] if struct.unpack_from('<I',obj.read_bytes(),68)[0] else []
    run([emitter,'--module',obj,name,source,'0x1bfec4',(heap_end-65536)&~16383,*extra])
if len(names)==1:
    # Re-emit the validated single-module size at its exact actual heap tail.
    size=json.loads((source/'gstate.json').read_text())['data_size']
    run([emitter,'--module',work/'out/jak1/obj/gstate.o','gstate',output,'0x1bfec4',(heap_end-size)&~16383])
    run([sys.executable,repo/'scripts/emit-signed-gstate-manifest.py',output,output/'manifest.cpp'])
else:
    # Preserve legacy placement; activation order remains canonical in metadata.
    placement=names if selected else (['gcommon','gstate','gstring'] if len(names)==3 else ['gstate','gstring'])
    inputs=[source/(name+'.json') for name in placement]
    span=sum((json.loads(path.read_text())['data_size']+15)&~15 for path in inputs)
    run([sys.executable,repo/'scripts/emit-signed-module-arena.py','--heap-start',heap_start,'--heap-end',heap_end,
         '--reservation-begin',(heap_end-span)&~16383,'--output',output,*inputs])
    run([sys.executable,repo/'scripts/emit-signed-gstate-manifest.py',output,output/'manifest.cpp','--aggregate',
         *(['--module-list',selected] if selected else [])])
PYTHON
  fi
  SIGNED_ARENA="aggregate-arena-layout.s"
  if [ "$SIGNED_NAMES" = gstate ]; then SIGNED_ARENA="gstate-arena-layout.s"; fi
  for artifact in "$SIGNED_INPUT_DIR/$SIGNED_ARENA" "$SIGNED_INPUT_DIR/manifest.cpp"; do
    if [ ! -s "$artifact" ]; then
      echo "Missing signed module artifact: $artifact; full build required" >&2; exit 1
    fi
  done
  compile "$WORKTREE/game/kernel/common/ottsel_signed_gstate.cpp" "$OBJ/signed_gstate.o"
  compile "$SIGNED_INPUT_DIR/manifest.cpp" "$OBJ/signed_manifest.o"
  xcrun --sdk "$SDK" clang "${COMMON_FLAGS[@]}" -c "$SIGNED_INPUT_DIR/$SIGNED_ARENA" -o "$OBJ/signed_arena.o"
  # ONE arena precedes every selected __GOAL input and optional export bank.
  SIGNED_OBJECTS=("$OBJ/signed_arena.o" "$OBJ/signed_manifest.o" "$OBJ/signed_gstate.o")
  for name in $SIGNED_NAMES; do
    if [ ! -s "$SIGNED_INPUT_DIR/$name.s" ]; then
      echo "Missing signed $name assembly; full build required" >&2; exit 1
    fi
    xcrun --sdk "$SDK" clang "${COMMON_FLAGS[@]}" -c "$SIGNED_INPUT_DIR/$name.s" -o "$OBJ/signed_${name}_code.o"
    SIGNED_OBJECTS+=("$OBJ/signed_${name}_code.o")
  done
  if [ "$SIGNED_EXPORT_BANKS" = 1 ]; then
    compile "$WORKTREE/game/kernel/common/ottsel_signed_exports.cpp" "$OBJ/signed_exports.o"
    python3 "$REPO_DIR/scripts/emit-signed-export-banks.py" "$SIGNED_DIR/export-banks.s"
    xcrun --sdk "$SDK" clang "${COMMON_FLAGS[@]}" -c "$SIGNED_DIR/export-banks.s" -o "$OBJ/signed_export_banks.o"
    SIGNED_OBJECTS+=("$OBJ/signed_exports.o" "$OBJ/signed_export_banks.o")
  fi
  SIGNED_OBJECTS+=(-Wl,-segprot,__ARENA,rw,rw -Wl,-segprot,__GOAL,rx,rx)
fi
compile "$REPO_DIR/src/shell/main.cpp" "$OBJ/shell_main.o"
compile "$REPO_DIR/src/shell/ios_boot.cpp" "$OBJ/ios_boot.o"
compile_objc "$REPO_DIR/src/shell/metal_shell.mm" "$OBJ/metal_shell.o"
compile_objc "$REPO_DIR/src/shell/metal_gfx.mm" "$OBJ/metal_gfx.o"
compile "$REPO_DIR/tools/ottsel_vu1/vu1.cpp" "$OBJ/vu1.o"
xcrun --sdk "$SDK" clang++ "${COMMON_FLAGS[@]}" -fobjc-arc \
  "${INCS[@]}" -I"$SLICE_DIR" -c "$REPO_DIR/src/shell/a11_slice_runner.mm" -o "$OBJ/a11_slice_runner.o"

xcrun --sdk "$SDK" clang++ "${COMMON_FLAGS[@]}" \
  ${SIGNED_OBJECTS[@]+"${SIGNED_OBJECTS[@]}"} \
  "$OBJ/shell_main.o" "$OBJ/ios_boot.o" "$OBJ/metal_shell.o" "$OBJ/metal_gfx.o" \
  "$OBJ/vu1.o" \
  "$OBJ/a11_slice_runner.o" "$OBJ/a11_slice.o" \
  -I"$SLICE_DIR" \
  "$APP_BUILD/libottsel-runtime.a" "$ZSTD_LIB" "$SDL_BUILD/libSDL3.a" \
  "${FRAMEWORKS[@]}" -lobjc \
  -o "$APP_BUILD/OttselShell"

echo "== [4/4] assemble + sign bundle =="
mkdir -p "$APP"
# The bundle must contain exactly what this step copies: the runtime loads KERNEL.CGO
# and GAME.CGO only, and an earlier round left an 18 MB stale ENGINE.CGO in the app
# that then rode along in every bundle since.  Clear the containers first.
rm -f "$APP"/*.CGO
cp "$APP_BUILD/OttselShell" "$APP/"
cp "$REPO_DIR/src/shell/Info.plist" "$APP/"
cp "$WORKTREE/out/jak1/iso/KERNEL.CGO" "$APP/KERNEL.CGO"
cp "$WORKTREE/out/jak1/iso/GAME.CGO" "$APP/GAME.CGO"
# Local Simulator research bundle only: the DGO/TEXT resources copied below
# include user-derived game assets. This is not a data-free distribution package.
# The release path must separate generated code from assets supplied via F1 import.
rm -rf "$APP/iso_data"
mkdir -p "$APP/iso_data"
# These complete containers mix recompiled title/start-sequence code with
# texture, art, and visibility objects. Keep the resulting bundle local.
mkdir -p "$APP/iso_data/DGO"
for dgo in TIT.DGO VI1.DGO; do
  if [ -f "$WORKTREE/out/jak1/iso/$dgo" ]; then
    cp "$WORKTREE/out/jak1/iso/$dgo" "$APP/iso_data/DGO/$dgo"
  fi
done
mkdir -p "$APP/iso_data/TEXT"
for text in "$WORKTREE"/out/jak1/iso/*.TXT; do
  if [ -f "$text" ]; then
    cp "$text" "$APP/iso_data/TEXT/"
  fi
done
plutil -lint "$APP/Info.plist" >/dev/null
if [ "$PLATFORM" = device ] && [ -n "${OTTSEL_SIGN_IDENTITY:-}" ] && [ -n "${OTTSEL_PROVISIONING_PROFILE:-}" ]; then
  # The bundle id and entitlements come from the profile so they always match it.
  cp "$OTTSEL_PROVISIONING_PROFILE" "$APP/embedded.mobileprovision"
  security cms -D -i "$OTTSEL_PROVISIONING_PROFILE" > "$APP_BUILD/profile.plist"
  /usr/libexec/PlistBuddy -x -c 'Print :Entitlements' "$APP_BUILD/profile.plist" > "$APP_BUILD/entitlements.plist"
  APP_ID="$(/usr/libexec/PlistBuddy -c 'Print :Entitlements:application-identifier' "$APP_BUILD/profile.plist")"
  BUNDLE_ID="${APP_ID#*.}"
  case "$BUNDLE_ID" in *'*'*) BUNDLE_ID="${OTTSEL_BUNDLE_ID:-com.ottsel.shell}" ;; esac
  /usr/libexec/PlistBuddy -c "Set :CFBundleIdentifier $BUNDLE_ID" "$APP/Info.plist"
  /usr/libexec/PlistBuddy -c 'Add :CFBundleSupportedPlatforms array' \
    -c 'Add :CFBundleSupportedPlatforms:0 string iPhoneOS' "$APP/Info.plist"
  codesign --force --sign "$OTTSEL_SIGN_IDENTITY" --entitlements "$APP_BUILD/entitlements.plist" "$APP"
  echo "signed for device: $BUNDLE_ID with $OTTSEL_SIGN_IDENTITY"
else
  codesign --force --sign - "$APP"
  if [ "$PLATFORM" = device ]; then
    echo "NOTE: ad-hoc signed; set OTTSEL_SIGN_IDENTITY and OTTSEL_PROVISIONING_PROFILE to install on a device" >&2
  fi
fi
codesign --verify --deep --strict "$APP"

# Publish a reusable cache identity only after the complete bundle verifies.
if ! $SHELL_ONLY; then
  SIGNED_RECORD_ARGS=("${SIGNED_PROFILE_ARGS[@]}")
  if $SIGNED_ENABLED; then SIGNED_RECORD_ARGS+=(--generation "$SIGNED_INPUT_DIR"); fi
  python3 "$REPO_DIR/scripts/signed-module-build-profile.py" record "${SIGNED_RECORD_ARGS[@]}"
  # Each full build emits a ~240 MB module generation. Keep the one just
  # recorded plus the three newest; older ones are unreferenced cache.
  if $SIGNED_ENABLED; then
    ls -1dt "$SIGNED_DIR"/modules.* 2>/dev/null | tail -n +4 | while read -r stale; do
      [ "$stale" = "$SIGNED_GENERATION" ] || rm -rf "$stale"
    done
  fi
fi

echo "OK: $APP"
ls -la "$APP"
