#!/bin/bash
# Ottsel S1.3 — build the iOS Simulator app with the no-emit runtime.
#
# Produces out/jak-project/out/ios/app/OttselShell.app (with KERNEL.CGO
# bundled as a resource) for the iPad Pro 11-inch (M4) Simulator.
#
# Layers:
#   1. SDL3 static for iphonesimulator arm64 (third-party/SDL via CMake)
#   2. runtime static lib: common (kernel subset) + game/kernel + sce +
#      mips2c table + ios_stubs, compiled with -DOTTSEL_NO_EMIT -DOTTSEL_IOS
#   3. the app: src/shell/main.cpp + src/shell/ios_boot.cpp
#   4. .app bundle + KERNEL.CGO resource + ad-hoc codesign
#
# Usage: scripts/build-ios.sh [--shell-only]
# --shell-only reuses the runtime, dependencies, and generated AOT slice from
# a prior full build. Run a full build first after nested runtime/GOAL changes
# (regenerating affected GOAL artifacts first), or toolchain/flag changes.
#
# OTTSEL_PLATFORM=device builds the same app for a physical iPhone/iPad
# (iphoneos SDK) into out/ios-device/. Set OTTSEL_SIGN_IDENTITY (an "Apple
# Development: ..." identity from `security find-identity -v -p codesigning`)
# and OTTSEL_PROVISIONING_PROFILE (a .mobileprovision file) to produce an
# installable bundle; without them the device build is ad-hoc signed.
#
# The app runs OpenGOAL's real IOP/OVERLORD thread (level, cutscene and audio
# streaming) exactly as desktop does (game/ottsel_ios_iop.cpp).

set -euo pipefail

SHELL_ONLY=false
case "${1:-}" in
  --shell-only) SHELL_ONLY=true ;;
  "") ;;
  *) echo "Usage: $0 [--shell-only]" >&2; exit 2 ;;
esac
if [ "$#" -gt 1 ]; then
  echo "Usage: $0 [--shell-only]" >&2
  exit 2
fi

REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
WORKTREE="$REPO_DIR/out/jak-project"
SDL_SRC="$WORKTREE/third-party/SDL"
PLATFORM="${OTTSEL_PLATFORM:-simulator}"
case "$PLATFORM" in
  simulator) IOS_OUT="$WORKTREE/out/ios" ;;
  device) IOS_OUT="$WORKTREE/out/ios-device" ;;
  *) echo "OTTSEL_PLATFORM must be simulator or device" >&2; exit 2 ;;
esac
SDL_BUILD="$IOS_OUT/sdl"
ZSTD_PROJECT="$WORKTREE/out/ios/zstd-project"
ZSTD_BUILD="$IOS_OUT/zstd-build"
ZSTD_LIB="$ZSTD_BUILD/zstd/liblibzstd_static.a"
APP_BUILD="$IOS_OUT/app"
OBJ="$APP_BUILD/obj"
APP="$APP_BUILD/OttselShell.app"
SLICE_DIR="$APP_BUILD/a11-slice"
# Optional canonical JSON module list; full KERNEL is not whole-game coverage.
SIGNED_GSTATE="${OTTSEL_SIGNED_GSTATE_EXPERIMENT:-0}"
SIGNED_MODULE_LIST="${OTTSEL_SIGNED_MODULE_LIST:-}"
SIGNED_EXPORT_BANKS="${OTTSEL_SIGNED_EXPORT_BANKS:-0}"
SIGNED_PROFILE_ARGS=(--repo "$REPO_DIR" --mode "$SIGNED_GSTATE" --banks "$SIGNED_EXPORT_BANKS")
if [ -n "$SIGNED_MODULE_LIST" ]; then
  # The helper resolves relative list paths against the repository root.
  SIGNED_PROFILE_ARGS+=(--list "$SIGNED_MODULE_LIST")
  case "$SIGNED_MODULE_LIST" in /*) ;; *) SIGNED_MODULE_LIST="$REPO_DIR/$SIGNED_MODULE_LIST" ;; esac
fi
SIGNED_NAMES="$(python3 "$REPO_DIR/scripts/signed-module-build-profile.py" names "${SIGNED_PROFILE_ARGS[@]}")"
SIGNED_ENABLED=false
if [ -n "$SIGNED_NAMES" ]; then SIGNED_ENABLED=true; fi
if $SHELL_ONLY && [ "$SIGNED_EXPORT_BANKS" != "$(cat "$APP_BUILD/signed-export-bank-mode" 2>/dev/null || echo 0)" ]; then
  echo "Signed export-bank mode changed; full build required" >&2; exit 1
fi
# Legacy numeric modes remain 0/1/2/3; lists never invent another numeric mode.
if $SHELL_ONLY && [ "$SIGNED_GSTATE" != "$(cat "$APP_BUILD/signed-gstate-mode" 2>/dev/null || echo 0)" ]; then
  echo "Signed Gstate mode changed; full build required" >&2; exit 1
fi
python3 "$REPO_DIR/scripts/signed-module-build-profile.py" preflight "${SIGNED_PROFILE_ARGS[@]}"
SIGNED_OBJECTS=()
SIGNED_DIR="$APP_BUILD/signed-gstate"
SIGNED_INPUT_DIR=""
if ! $SHELL_ONLY; then
  # A failed full build must not leave an earlier generation reusable.
  rm -f "$APP_BUILD/signed-module-profile.json"
fi
if $SHELL_ONLY; then
  # Check exact selection, source/KERNEL members and cached generated bytes
  # before even resolving the SDK, and therefore before any compiler call.
  SIGNED_INPUT_DIR="$(python3 "$REPO_DIR/scripts/signed-module-build-profile.py" check "${SIGNED_PROFILE_ARGS[@]}")"
fi

if $SHELL_ONLY; then
  for artifact in "$SDL_BUILD/libSDL3.a" "$ZSTD_LIB" \
    "$APP_BUILD/libottsel-runtime.a" "$OBJ/a11_slice.o" \
    "$SLICE_DIR/a11_slice_map.h" \
    "$WORKTREE/out/jak1/iso/KERNEL.CGO" "$WORKTREE/out/jak1/iso/GAME.CGO"; do
    if [ ! -s "$artifact" ]; then
      echo "Shell-only prerequisite missing or empty: $artifact" >&2
      echo "Run scripts/build-ios.sh without --shell-only first." >&2
      exit 1
    fi
  done
  echo "== Reusing existing runtime, dependency libraries, and AOT slice =="
fi

SDK=iphonesimulator26.5
DEPLOY=18.5
TARGET=arm64-apple-ios$DEPLOY-simulator
if [ "$PLATFORM" = device ]; then
  SDK=iphoneos
  TARGET=arm64-apple-ios$DEPLOY
fi
SDKROOT="$(xcrun --sdk "$SDK" --show-sdk-path)"

COMMON_FLAGS=(-std=c++20 -O2 -fno-omit-frame-pointer -D_CRT_SECURE_NO_WARNINGS -D_XOPEN_SOURCE \
  -DOTTSEL_NO_EMIT -DOTTSEL_IOS \
  -target "$TARGET" -isysroot "$SDKROOT" -mios-version-min="$DEPLOY")
if $SIGNED_ENABLED; then
  COMMON_FLAGS+=(-DOTTSEL_SIGNED_GSTATE_EXPERIMENT)
fi
if [ "$SIGNED_EXPORT_BANKS" = 1 ]; then
